//! 注册表驱动的完整契约生成源（contract-registry-v2-04-full-contract-generation）。
//!
//! 消费 `novel_cli::contracts::register_contracts()`（命令语义唯一结构化来源）、
//! `novel_cli::errors::catalog::ErrorCatalog::ENTRIES`（错误语义唯一来源）与
//! `commands_source::collect_commands()`（clap 叶子，语法唯一来源），生成：
//!
//! - `commands.md` 各命令的行为语义段 + 退出码表（替代手写段）；
//! - `contracts/cli/command-error-matrix.md`（命令 × 错误 ID × 类别 × 退出码矩阵）；
//! - `contracts/cli/examples/INDEX.md`（示例/fixture 索引）；
//! - `contracts/cli/contract-tests/INDEX.md`（契约测试索引）。
//!
//! 边界（CLAUDE.md §3/§6/§8）：spec-gen 是 dev-only xtask，本模块只读注册表静态数据、
//! `ErrorCatalog`、clap 树与 `contracts/cli/` 既有文件，不读 SQLite、不读 `.novel/content`。
//!
//! 设计决策（见 openspec/changes/contract-registry-v2-04-full-contract-generation/design.md）：
//! - D1 扩展 `spec-gen`（registry_source 模块）而非新建 crate，延用 lib 消费 novel_cli。
//! - D2 行为语义/退出码表由注册表 + ErrorCatalog 派生；叙述映射键集合由目录校准。
//! - D3 错误矩阵 / examples / fixtures / 契约测试索引为受控生成物（`@generated` 标记界定）。
//! - D4 漂移门禁扩展为六类受控产物全量覆盖。
//! - D5 反向一致性校验 `check_index_consistency()` 单一函数，与注册表/目录/文件系统交叉。

use std::collections::BTreeMap;
use std::path::Path;

use novel_cli::contracts::{OutputContract, register_contracts};
use novel_cli::errors::catalog::ErrorCatalog;

use crate::md_render::GEN_END;

// ── 遍历辅助（task 1.1）──────────────────────────────────────────────────

/// 注册表按命令路径索引：`command_path -> CommandContract`。
///
/// 命令路径为完整叶子路径（如 `volume goal set`，不含 `novel`），与 clap 叶子一一对应。
pub fn registry_index() -> BTreeMap<&'static str, &'static novel_cli::contracts::CommandContract> {
    register_contracts()
        .iter()
        .map(|c| (c.command_path, c))
        .collect()
}

/// 错误 ID → 类别 → 退出码派生映射：`error_id -> (category_str, exit_code)`。
///
/// 类别与退出码的唯一来源为 `ErrorCatalog::ENTRIES`（错误语义唯一来源），
/// 退出码 = `ErrorCategory::exit_code()` 的派生值。目录外 ID 不在映射内。
pub fn error_category_map() -> BTreeMap<&'static str, (&'static str, i32)> {
    ErrorCatalog::ENTRIES
        .iter()
        .map(|e| (e.id, (e.category.as_str(), e.exit_code())))
        .collect()
}

/// 注册表输出定义引用的全部 schema 名集合（`OutputContract::JsonSchema(name)`）。
///
/// 供索引渲染与反向一致性校验复用：schema 引用 MUST 在 `json-schemas/` 存在。
pub fn referenced_schemas() -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for c in register_contracts() {
        for o in c.outputs {
            if let OutputContract::JsonSchema(name) = o {
                out.push(name);
            }
        }
    }
    out.sort_unstable();
    out.dedup();
    out
}

/// 收集 `json-schemas/*.schema.json` 的文件基名集合（含 .schema.json 后缀）。
fn schemas_on_disk(repo_root: &Path) -> Vec<String> {
    let dir = repo_root.join("contracts/cli/json-schemas");
    let mut out = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.ends_with(".schema.json") {
                out.push(name);
            }
        }
    }
    out.sort();
    out
}

/// markdown 表格单元格转义（`|` → `\|`）。
fn esc(s: &str) -> String {
    s.replace('|', "\\|")
}

// ── 命令错误矩阵渲染（task 1.2）────────────────────────────────────────────

/// 渲染 `command-error-matrix.md` 完整内容（含 `@generated` 标记头）。
///
/// 每行 = 命令路径 × 可返回错误 ID × 错误类别 × 退出码。错误 ID 来自注册表记录
/// `errors` 字段，类别/退出码来自 `ErrorCatalog` 条目派生；矩阵不定义新错误语义。
pub fn render_error_matrix(repo_root: &Path) -> String {
    let cat_map = error_category_map();
    let mut s = String::new();
    s.push_str("<!-- @generated by spec-gen registry_source. DO NOT EDIT. -->\n");
    s.push_str("<!-- 命令错误矩阵：命令路径 × 可返回错误 ID × 错误类别 × 退出码。 -->\n");
    s.push_str("<!-- 错误 ID 唯一源：CommandContract 注册表 errors 字段；类别/退出码唯一源：ErrorCatalog::ENTRIES 派生。 -->\n");
    s.push_str("| 命令路径 | 可返回错误 ID | 错误类别 | 退出码 |\n");
    s.push_str("|---|---|---|---|\n");
    for c in register_contracts() {
        for e in c.errors {
            let id = e.as_str();
            let (cat, exit) = cat_map.get(id).copied().unwrap_or(("（目录外）", -1));
            s.push_str(&format!(
                "| `{}` | `{}` | {} | `{}` |\n",
                esc(c.command_path),
                id,
                esc(cat),
                if exit >= 0 { exit.to_string() } else { "（未登记）".to_string() }
            ));
        }
    }
    s.push_str(GEN_END);
    s.push('\n');
    // 抑制未使用告警（repo_root 供后续扩展引用 json-schemas 清单，保留签名一致性）。
    let _ = schemas_on_disk(repo_root);
    s
}

// ── commands.md 行为语义 + 退出码表渲染（task 1.3）────────────────────────

/// 渲染单命令的「行为语义 + 退出码」生成段（`@generated` 标记界定）。
///
/// 行为语义主干来自注册表记录：`summary` 为语义首句，`inputs`/`outputs` 约束为要点，
/// `guard` 引用为状态机/守卫关联。退出码表行来自注册表 `errors` 引用集合，退出码由
/// `ErrorCatalog` 条目类别派生，表为可追踪概要而非第二份退出码 SSOT。
pub fn render_command_semantics_block(
    path: &str,
    contract: &novel_cli::contracts::CommandContract,
) -> String {
    let cat_map = error_category_map();
    let mut s = String::new();
    s.push_str("<!-- @generated by spec-gen registry_source. DO NOT EDIT. -->\n");
    s.push_str("<!-- 行为语义主干源：CommandContract 注册表（summary/inputs/outputs/guard）；退出码表源：注册表 errors × ErrorCatalog 派生。 -->\n");
    s.push_str("### 行为语义\n\n");
    s.push_str(&format!("- {}\n", esc(contract.summary)));
    for input in contract.inputs {
        s.push_str(&format!(
            "- 输入约束 `{}`：{}\n",
            esc(input.slot),
            esc(input.constraint)
        ));
    }
    for output in contract.outputs {
        let desc = match output {
            OutputContract::JsonSchema(schema) => {
                format!("稳定 JSON 输出（`contracts/cli/json-schemas/{schema}.schema.json`）")
            }
            OutputContract::HumanReadable => "人读输出（无稳定 JSON schema）".to_string(),
            OutputContract::SilentSuccess => "静默成功（无输出）".to_string(),
        };
        s.push_str(&format!("- 输出形态：{}\n", desc));
    }
    for guard in contract.guard {
        s.push_str(&format!("- 状态机/guard 引用：`{}`\n", esc(guard.target)));
    }
    s.push('\n');
    s.push_str("### 退出码\n\n");
    s.push_str("> 权威来源：退出码与错误语义的 SSOT 见 `exit-codes.md` / `error-codes.md` / `ErrorCatalog`。本表为注册表驱动生成的可追踪概要，若与 SSOT 冲突以 SSOT 为准。\n\n");
    s.push_str("| 错误 ID | 错误类别 | 退出码 |\n");
    s.push_str("|---|---|---|\n");
    for e in contract.errors {
        let id = e.as_str();
        let (cat, exit) = cat_map.get(id).copied().unwrap_or(("（目录外）", -1));
        s.push_str(&format!(
            "| `{}` | {} | `{}` |\n",
            id,
            esc(cat),
            if exit >= 0 { exit.to_string() } else { "（未登记）".to_string() }
        ));
    }
    // 成功场景行（命令成功退出码 0）。
    s.push_str("| `-`（成功） | 成功 | `0` |\n");
    s.push_str(GEN_END);
    s.push('\n');
    let _ = path;
    s
}

/// 将注册表行为语义 + 退出码生成段注入 `commands.md`，替换手写段。
///
/// 复用 `commands_source` 的生成段替换策略：在每个命令标题（`## \`novel ...\``）下，
/// 语法段（`commands_source` 生成）保持原位，把「行为语义 + 退出码」手写段替换为
/// 注册表驱动的生成段。`@generated` 标记外的补充说明（如 `init` 目录结构长叙述）
/// 保留手写（drift 只锁标记内）。
pub fn apply_command_semantics_blocks(content: &str) -> String {
    let index = registry_index();
    let lines: Vec<&str> = content.lines().collect();
    let mut out = String::new();
    let mut i = 0;
    while i < lines.len() {
        let line = lines[i];
        if let Some(name) = extract_command_name(line) {
            out.push_str(line);
            out.push('\n');
            i += 1;
            // 复制该命令体直到下一命令标题，期间：
            // - 语法生成段（`@generated by spec-gen commands_source`）原样保留；
            // - 手写「行为语义」/「退出码」段（及其后的旧手写内容）替换为生成段；
            // - `@generated by spec-gen registry_source`（幂等重生成）原位替换。
            let mut seen_semantics = false;
            let mut body = String::new();
            while i < lines.len() && extract_command_name(lines[i]).is_none() {
                let l = lines[i];
                let is_reg_marker = l.trim_start().starts_with("<!-- @generated by spec-gen registry_source");
                let is_syntax_marker = l.trim_start().starts_with("<!-- @generated by spec-gen commands_source");
                if is_syntax_marker {
                    // 语法生成段：整段保留（到 GEN_END）。
                    body.push_str(l);
                    body.push('\n');
                    i += 1;
                    while i < lines.len() && !lines[i].contains(GEN_END) {
                        body.push_str(lines[i]);
                        body.push('\n');
                        i += 1;
                    }
                    if i < lines.len() {
                        body.push_str(lines[i]);
                        body.push('\n');
                        i += 1;
                    }
                    continue;
                }
                if is_reg_marker {
                    // 幂等重生成：以当前注册表内容重新注入生成段，替换旧生成段
                    // （跳过到旧 GEN_END）。补充叙述随后原样保留。
                    if let Some(contract) = index.get(name) {
                        body.push_str(&render_command_semantics_block(name, contract));
                    }
                    seen_semantics = true;
                    while i < lines.len() && !lines[i].contains(GEN_END) {
                        i += 1;
                    }
                    if i < lines.len() {
                        i += 1;
                    }
                    continue;
                }
                // 手写「行为语义」或「退出码」标题：注入注册表生成段一次。
                // - 「行为语义」标题下的补充叙述（注册表 summary/inputs/outputs 未覆盖的
                //   详细行为，如 JSON 字段结构、具体退出码场景）保留为豁免段（@generated
                //   标记外，drift 不比对，措辞可人工维护，见 cli-contract spec「补充说明」）；
                // - 旧「退出码」段（手写退出码表）被生成段替代，整段跳过。
                // 标题判定须为 md 标题行（### 前缀）——行为语义 bullet 内嵌「退出码」字样
                // （如「否则退出码 2」）不触发，否则补充收集被误截断。
                let is_semantics_heading = l.trim_start().starts_with('#') && l.contains("行为语义");
                let is_exit_codes_heading = l.trim_start().starts_with('#') && l.contains("退出码");
                if !seen_semantics && (is_semantics_heading || is_exit_codes_heading) {
                    if let Some(contract) = index.get(name) {
                        body.push_str(&render_command_semantics_block(name, contract));
                        seen_semantics = true;
                    }
                    let was_semantics_heading = is_semantics_heading;
                    i += 1;
                    let mut supplement = String::new();
                    if was_semantics_heading {
                        // 收集补充叙述直到旧「退出码」标题 / 命令标题 / 生成标记。
                        while i < lines.len() && extract_command_name(lines[i]).is_none() {
                            let nl = lines[i];
                            let is_marker = nl.trim_start().starts_with("<!-- @generated by spec-gen");
                            let is_exit_heading =
                                nl.trim_start().starts_with('#') && nl.contains("退出码");
                            if is_marker || is_exit_heading {
                                break;
                            }
                            supplement.push_str(nl);
                            supplement.push('\n');
                            i += 1;
                        }
                        if !supplement.trim().is_empty() {
                            body.push('\n');
                            body.push_str(&supplement);
                            body.push('\n');
                        }
                    }
                    // 跳过旧「退出码」段（手写退出码表）直到下一命令标题。
                    while i < lines.len() && extract_command_name(lines[i]).is_none() {
                        i += 1;
                    }
                    continue;
                }
                // 其他行（描述、补充说明、空行）：原样保留。
                body.push_str(l);
                body.push('\n');
                i += 1;
            }
            // 命令体末尾：规范化为单空行分隔（trim_end 后补一个空行）。
            // 首次注入与幂等重生成两条路径对补充段前后空行处理不对称会累积空行，
            // 统一收尾保证重生成幂等（体尾恰一个空行，命令标题前一个空行）。
            if !body.trim_end().is_empty() {
                out.push_str(body.trim_end());
                out.push('\n');
                out.push('\n');
            }
            continue;
        }
        out.push_str(line);
        out.push('\n');
        i += 1;
    }
    out
}

/// 从 `## \`novel ...\`` 标题行提取命令名（如 `setting set`）。
fn extract_command_name(line: &str) -> Option<&str> {
    let line = line.trim_start();
    let inner = line.strip_prefix("## `novel ")?;
    inner.strip_suffix('`')
}

// ── 示例/fixture 索引渲染（task 1.4）───────────────────────────────────────

/// 渲染 `examples/INDEX.md`：示例/fixture 的可检索索引。
///
/// 以文件系统清单 + 注册表输出定义（`OutputContract::JsonSchema`）驱动，非手写登记。
/// 文件命名前缀 ↔ 命令路径映射：`<command-prefix>-...`（如 `info.golden.json` → `info`、
/// `setting-not-found.error.golden.json` → `setting get` 族）。schema 引用取自注册表。
pub fn render_examples_index(repo_root: &Path) -> String {
    let examples_dir = repo_root.join("contracts/cli/examples");
    let fixtures_dir = repo_root.join("contracts/cli/fixtures");
    let index = registry_index();

    let mut example_files: Vec<String> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&examples_dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name != "INDEX.md" && !name.starts_with('.') {
                example_files.push(name);
            }
        }
    }
    example_files.sort();

    let mut fixture_files: Vec<String> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&fixtures_dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name != "README.md" && !name.starts_with('.') {
                fixture_files.push(name);
            }
        }
    }
    fixture_files.sort();

    let mut s = String::new();
    s.push_str("<!-- @generated by spec-gen registry_source. DO NOT EDIT. -->\n");
    s.push_str("<!-- 示例/fixture 索引：以文件系统清单 + CommandContract 注册表输出定义驱动，非手写登记。 -->\n");
    s.push_str("<!-- 新增/删除/重命名示例或 fixture 文件后运行 `cargo run -p spec-gen -- generate` 重新生成。 -->\n");
    s.push_str("## 示例（golden / fixture 引用）\n\n");
    s.push_str("| 示例文件 | 关联命令路径 | schema 引用 |\n");
    s.push_str("|---|---|---|\n");
    for f in &example_files {
        let (cmd, schema) = map_example_to_command(f, &index);
        let cmd_disp = cmd.as_ref().map(|c| format!("`{}`", esc(c))).unwrap_or("（未匹配）".to_string());
        let schema_disp = schema.map(|s| format!("`{}.schema.json`", s)).unwrap_or("—".to_string());
        s.push_str(&format!("| `{}` | {} | {} |\n", f, cmd_disp, schema_disp));
    }
    s.push('\n');
    s.push_str("## fixture 脚本\n\n");
    s.push_str("| fixture 脚本 | 说明（依赖） |\n");
    s.push_str("|---|---|\n");
    for f in &fixture_files {
        s.push_str(&format!("| `{}` | 见 fixtures/README.md |\n", f));
    }
    s.push_str(GEN_END);
    s.push('\n');
    s
}

/// 示例文件 → (关联命令路径, schema 引用名) 映射。
///
/// 两级匹配：
/// 1. **最长前缀精确匹配**：规范化文件名 stem（去掉 `.error.golden.json` /
///    `.output.golden.json` / `.golden.json` / `.json` / `.txt` 后缀，`-` 视为空格）后，
///    找以该 stem 开头的最长注册表 `command_path`（如 `constraint-render-view-chapter`
///    → `constraint render`）。
/// 2. **族回退**：无精确匹配时取文件名首段（如 `setting-not-found` → `setting`）作为
///    命令族，映射到该族首条命令（仍可追踪到命令域，如 `setting get`）。
///
/// schema 引用取命中命令 `OutputContract::JsonSchema` 的首个（若有）。
fn map_example_to_command(
    f: &str,
    index: &BTreeMap<&'static str, &'static novel_cli::contracts::CommandContract>,
) -> (Option<String>, Option<&'static str>) {
    // 规范化文件名 stem：剥掉后缀，`-` 归一为空格（对齐 command_path 的空格分隔）。
    let stem = f
        .trim_end_matches(".error.golden.json")
        .trim_end_matches(".output.golden.json")
        .trim_end_matches(".golden.json")
        .trim_end_matches(".json")
        .trim_end_matches(".txt")
        .replace('-', " ");

    // 1. 最长前缀匹配：候选 = 注册表 command_path 中「stem 以 path 开头」的记录，取最长者。
    let mut best: Option<&'static str> = None;
    let mut best_len = 0usize;
    for path in index.keys() {
        if stem.starts_with(path) && path.len() > best_len {
            best = Some(path);
            best_len = path.len();
        }
    }
    let cmd = best.map(|p| p.to_string());

    // 2. 族回退：取 stem 首词作为命令族前缀，映射到该族首条命令（BTreeMap 序）。
    let cmd = cmd.or_else(|| {
        let first = stem.split(' ').next().unwrap_or("");
        index
            .keys()
            .find(|p| p.starts_with(first))
            .map(|p| p.to_string())
    });

    let schema = cmd
        .as_ref()
        .and_then(|c| index.get(c.as_str()))
        .and_then(|contract| {
            contract
                .outputs
                .iter()
                .find_map(|o| match o {
                    OutputContract::JsonSchema(s) => Some(*s),
                    _ => None,
                })
        });
    (cmd, schema)
}

// ── 契约测试索引渲染（task 1.5）───────────────────────────────────────────

/// 从 `novel-cli/Cargo.toml` 提取 `[[test]]` 注册的 `name` → `path` 映射。
fn cargo_test_entries(repo_root: &Path) -> Vec<(String, String)> {
    let path = repo_root.join("crates/novel-cli/Cargo.toml");
    let content = std::fs::read_to_string(&path).unwrap_or_default();
    let mut out = Vec::new();
    let mut in_test = false;
    let mut name = String::new();
    let mut test_path = String::new();
    for line in content.lines() {
        let t = line.trim();
        if t.starts_with("[[test]]") {
            if in_test && !name.is_empty() {
                out.push((name.clone(), test_path.clone()));
            }
            in_test = true;
            name.clear();
            test_path.clear();
            continue;
        }
        if in_test {
            if let Some(v) = t.strip_prefix("name = ") {
                name = v.trim().trim_matches('"').to_string();
            }
            if let Some(v) = t.strip_prefix("path = ") {
                test_path = v.trim().trim_matches('"').to_string();
            }
        }
    }
    if in_test && !name.is_empty() {
        out.push((name, test_path));
    }
    out
}

/// 渲染 `contract-tests/INDEX.md`：契约测试索引。
///
/// 遍历 `contract-tests/*.rs` 与 `generated/*.gen.rs` 文件系统清单 + `Cargo.toml [[test]]`
/// 注册，生成「测试文件 ↔ 命令覆盖 ↔ 生成源」消费清单。未注册测试文件被 `check_index_consistency`
/// 捕获（本函数只登记，校验归单一函数）。
pub fn render_test_index(repo_root: &Path) -> String {
    let contract_tests_dir = repo_root.join("contracts/cli/contract-tests");
    let generated_dir = repo_root.join("contracts/cli/generated");
    let cargo = cargo_test_entries(repo_root);

    let mut test_files: Vec<String> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&contract_tests_dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.ends_with(".rs") {
                test_files.push(name);
            }
        }
    }
    test_files.sort();
    let mut gen_files: Vec<String> = Vec::new();
    if let Ok(rd) = std::fs::read_dir(&generated_dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name.ends_with(".gen.rs") {
                gen_files.push(name);
            }
        }
    }
    gen_files.sort();

    let mut s = String::new();
    s.push_str("<!-- @generated by spec-gen registry_source. DO NOT EDIT. -->\n");
    s.push_str("<!-- 契约测试索引：文件系统清单 + Cargo.toml [[test]] 注册，标注生成源手写/@codegen 与覆盖命令域。 -->\n");
    s.push_str("<!-- 新增/删除/重命名测试文件后运行 `cargo run -p spec-gen -- generate` 重新生成。 -->\n");
    s.push_str("## 手写契约测试（contract-tests/*.rs）\n\n");
    s.push_str("| 测试文件 | 生成源 | Cargo [[test]] 注册 |\n");
    s.push_str("|---|---|---|\n");
    for f in &test_files {
        let registered = if cargo.iter().any(|(_, p)| p.ends_with(&format!("contract-tests/{f}"))) {
            "✓"
        } else {
            "✗"
        };
        s.push_str(&format!("| `{}` | 手写 | {} |\n", f, registered));
    }
    s.push('\n');
    s.push_str("## 生成式契约测试（generated/*.gen.rs）\n\n");
    s.push_str("| 测试文件 | 生成源 | Cargo [[test]] 注册 |\n");
    s.push_str("|---|---|---|\n");
    for f in &gen_files {
        let registered = if cargo.iter().any(|(_, p)| p.ends_with(&format!("generated/{f}"))) {
            "✓"
        } else {
            "✗"
        };
        s.push_str(&format!("| `{}` | `@codegen` | {} |\n", f, registered));
    }
    s.push_str(GEN_END);
    s.push('\n');
    s
}

// ── 反向一致性校验（task 1.6）─────────────────────────────────────────────

/// 反向一致性校验（单一校验函数，design D5）。
///
/// 在 `validate_registry()`（slice 03）基础上补充四类反向检查，返回不一致报告
/// （空 Vec 表示一致）：
/// 1. schema 引用可解析：注册表 `OutputContract::JsonSchema(name)` 引用的 `name.schema.json`
///     MUST 存在于 `contracts/cli/json-schemas/`；
/// 2. 错误矩阵行错误 ID 均 ∈ `ErrorCatalog`（`validate_registry` 已查注册表引用合法性，
///    此处再锁矩阵渲染所用类别映射覆盖）；
/// 3. 契约测试文件（`contract-tests/*.rs` + `generated/*.gen.rs`）MUST 在 `Cargo.toml`
///     `[[test]]` 注册；
/// 4. 示例文件可追溯命令（按 `map_example_to_command` 映射；无法匹配即报不一致）。
///
/// 被 `generate` 与 `check` 复用，MUST NOT 存在第二份独立实现。
pub fn check_index_consistency(repo_root: &Path) -> Vec<String> {
    let mut issues = Vec::new();

    // 1. schema 引用可解析。
    let on_disk = schemas_on_disk(repo_root);
    for schema in referenced_schemas() {
        let fname = format!("{schema}.schema.json");
        if !on_disk.contains(&fname) {
            issues.push(format!("注册表引用的 schema 不存在: {fname}"));
        }
    }

    // 2. 错误矩阵类别映射覆盖：注册表引用的全部错误 ID 均 ∈ ErrorCatalog（目录派生）。
    let cat_map = error_category_map();
    for c in register_contracts() {
        for e in c.errors {
            if !cat_map.contains_key(e.as_str()) {
                issues.push(format!(
                    "命令 {} 引用的错误 ID {} 不在 ErrorCatalog（矩阵无法派生类别/退出码）",
                    c.command_path,
                    e.as_str()
                ));
            }
        }
    }

    // 3. 契约测试文件 ∈ Cargo.toml [[test]] 注册。
    let contract_tests_dir = repo_root.join("contracts/cli/contract-tests");
    let generated_dir = repo_root.join("contracts/cli/generated");
    let cargo = cargo_test_entries(repo_root);
    let mut check_registration = |dir: &Path, suffix: &str| {
        if let Ok(rd) = std::fs::read_dir(dir) {
            for entry in rd.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if !name.ends_with(suffix) {
                    continue;
                }
                let registered = cargo.iter().any(|(_, p)| p.ends_with(&name));
                if !registered {
                    issues.push(format!("契约测试文件未在 Cargo.toml [[test]] 注册: {name}"));
                }
            }
        }
    };
    check_registration(&contract_tests_dir, ".rs");
    check_registration(&generated_dir, ".gen.rs");

    // 4. 示例文件可追溯命令。
    let examples_dir = repo_root.join("contracts/cli/examples");
    let index = registry_index();
    if let Ok(rd) = std::fs::read_dir(&examples_dir) {
        for entry in rd.flatten() {
            let name = entry.file_name().to_string_lossy().to_string();
            if name == "INDEX.md" || name.starts_with('.') {
                continue;
            }
            let (cmd, _) = map_example_to_command(&name, &index);
            if cmd.is_none() {
                issues.push(format!("示例文件无法追溯到注册表命令: {name}"));
            }
        }
    }

    issues
}

// ── check 路径辅助（task 2.2）──────────────────────────────────────────────

/// 整文件 drift 比对：生成物为受控全文（`command-error-matrix.md`、`examples/INDEX.md`、
/// `contract-tests/INDEX.md`），在内存重新生成后与仓库逐字比对。返回 `true` 表示漂移。
///
/// 这三类生成物是「整文件生成」——无手写豁免段，全内容由生成器产出，手改任一行即 drift 红。
pub fn check_full_file_drift(path: &Path, expected: &str) -> bool {
    let on_disk = std::fs::read_to_string(path).unwrap_or_default();
    on_disk != expected
}

/// 提取某命令的 `registry_source` 生成段（`<!-- @generated by spec-gen registry_source ... -->`
/// 到 `<!-- /@generated -->`，含标记）。无该段返回 `None`。
///
/// 与 `render_command_semantics_block` 输出逐字对齐：渲染末尾含 `GEN_END + '\n'`，
/// 提取也包含 GEN_END 后的换行（不吞掉与补充叙述的分隔空行）。
fn extract_registry_block(content: &str, name: &str) -> Option<String> {
    let heading = format!("## `novel {name}`");
    let hstart = content.find(&heading)?;
    let rest = &content[hstart..];
    let mstart = rest.find("<!-- @generated by spec-gen registry_source")?;
    let after = &rest[mstart..];
    let mend = after.find(GEN_END)?;
    let mut end = mend + GEN_END.len();
    if after[end..].starts_with('\n') {
        end += 1;
    }
    Some(after[..end].to_string())
}

/// `commands.md` 行为语义/退出码生成段 drift：对每个注册表命令，提取仓库文件中的
/// `registry_source` 生成段并与期望逐字比对（`@generated` 标记内全部锁定）。返回漂移命令名列表。
pub fn check_semantics_drift(path: &Path) -> Vec<String> {
    let index = registry_index();
    let on_disk = std::fs::read_to_string(path).unwrap_or_default();
    let mut drifts = Vec::new();
    for (name, contract) in &index {
        let expected = render_command_semantics_block(name, contract);
        match extract_registry_block(&on_disk, name) {
            Some(actual) if actual == expected => {}
            Some(_) => drifts.push(format!("commands.md 行为语义/退出码段（{}）", name)),
            None => drifts.push(format!("commands.md 缺 registry_source 生成段（{}）", name)),
        }
    }
    drifts
}

/// 叙述映射键集合校准：md_render 侧叙述映射（exit 叙述 / error 叙述）的键集合 MUST
/// 与 enum/目录派生集合一致。未知键（enum 无对应叙述）或缺失键（enum 有变体但叙述映射
/// 缺条目）均视为 drift 红；叙述措辞本身仍人可手改（drift 只锁键集合）。
///
/// 键集合校准把「叙述映射表」从自由手写升级为受 enum 派生集合约束的映射——enum 源删除
/// 变体后叙述残留（未知键）或 enum 新增变体后叙述未补（缺失键）都会阻断 check。
pub fn check_narrative_keys_drift(
    maps: &crate::enum_source::EnumSourceMaps,
) -> Vec<String> {
    let mut issues = Vec::new();

    // exit 叙述键集合（md_render::exit_narrative） vs ExitCode 变体集合。
    let exit_keys: std::collections::BTreeSet<i32> = maps.exit_codes.iter().map(|e| e.code).collect();
    let narrative_exit_keys: std::collections::BTreeSet<i32> =
        maps.exit_codes.iter().map(|e| e.code).filter(|c| crate::md_render::exit_category(*c).is_some()).collect();
    for k in exit_keys.difference(&narrative_exit_keys) {
        issues.push(format!("exit-codes 叙述映射缺失键：退出码 {k}（enum 有变体但叙述未登记）"));
    }

    // error 叙述键集合（md_render::error_narrative） vs ErrorCode 串集合：
    // enum 有变体但叙述映射缺条目（缺失键）即 drift 红。未知键场景（叙述残留 enum 已删）
    // 由渲染层兜底防御 + 枚举源即唯一来源保证——叙述映射只被渲染遍历消费，无独立遍历入口，
    // 残留键不产生生成物，故未知键无可漂移载体；缺失键是唯一可测方向。
    for e in &maps.error_codes {
        if !crate::md_render::has_error_narrative(e.code) {
            issues.push(format!("error-codes 叙述映射缺失键：错误码 {}（enum 有变体但叙述未登记）", e.code));
        }
    }
    issues
}

