//! 枚举类型化契约源（contract-governance-02-error-enum-gen）。
//!
//! 把 `novel-cli` 的 `ExitCode` / `ErrorCode` enum 提升为错误契约的类型化源，
//! spec-gen 遍历变体取出「机器可导出列」，替代靠正则解析散文 md 的现状。
//!
//! 生成范围（design Q1 决议）：只生成机器可导出的数值与字符串列，不生成人读叙述：
//! - `exit-codes.md` §A 「退出码」列 ← `ExitCode::iter()` 判别式（`*variant as i32`）
//! - `error-codes.md` §A 「错误码」列 ← `ErrorCode::iter()` 经 `IntoStaticStr` 序列化名
//! - `error-codes.md` §A 「对应退出码」列 ← `ErrorCatalog` 类别派生（05 治理 V2 默认，
//!   退出码由错误类别唯一派生，V1 per-entity aliases 已退役）
//!
//! 中文「类别 / 含义 / 固化切片」叙述列仍手写（非 enum 可导出，不纳入生成）。
//! 生成物用于与手写 md 对账：手写 md 的退出码数值 / 错误码字符串集合若与 enum 源
//! 不一致，视为 md 漂移，按「以 errors/mod.rs::exit_code() 为权威改 md」修正。
//!
//! 边界（CLAUDE.md §3/§8）：spec-gen 是 dev-only xtask，以 lib 形式消费 novel-cli 的
//! enum 源，不读 SQLite、不读 `.novel/content`，不绕过 CLI。本模块只读 enum 变体声明，
//! 属编译期类型化数据，无运行期世界状态。

use strum::IntoEnumIterator;

pub use novel_cli::errors::{ErrorCatalog, ErrorCode, ExitCode};

/// 一条退出码的机器可导出记录：数值 + PascalCase 变体名（变体名仅供 spec-gen 报告，
/// 非 `exit-codes.md` 契约字符串——退出码无字符串契约，见 design D1/Q1）。
#[derive(Debug, Clone)]
pub struct ExitCodeEntry {
    pub code: i32,
    pub variant: &'static str,
}

/// 一条错误码的机器可导出记录：strum serialize 字符串（契约串）+ 其声称对应的退出码数值。
#[derive(Debug, Clone)]
pub struct ErrorCodeEntry {
    pub code: &'static str,
    pub stated_exit: i32,
}

/// 从 enum 源构建的机器可导出映射集。
#[derive(Debug, Default)]
pub struct EnumSourceMaps {
    /// 退出码数值 → 变体名（来源 `ExitCode::iter()` 判别式）。
    pub exit_codes: Vec<ExitCodeEntry>,
    /// 错误码字符串 → 声称退出码（来源 `ErrorCode::iter()` 序列化名 + aliases）。
    pub error_codes: Vec<ErrorCodeEntry>,
}

/// 遍历 `ExitCode` / `ErrorCode` 变体，构建机器可导出映射集。
///
/// - 退出码数值唯一源：`ExitCode` 变体显式判别式（`*v as i32`），不重复编码数值。
/// - 错误码字符串唯一源：`ErrorCode` 经 `IntoStaticStr` 的 `From<ErrorCode> for &'static str`
///   （遵守 `#[strum(serialize)]` 注解，逐字等于原手写 `as_str()`）。
/// - 错误码→退出码映射：spec-gen 侧 `error_code_to_exit()` aliases 声明（design D3/Q2），
///   errors 层 `exit_code()` 保持唯一权威，本模块不向 errors 层新增映射表。
pub fn load_enum_source() -> EnumSourceMaps {
    let exit_codes: Vec<ExitCodeEntry> = ExitCode::iter()
        .map(|v| ExitCodeEntry {
            code: v as i32,
            variant: variant_name_exit(v),
        })
        .collect();

    let mut error_codes: Vec<ErrorCodeEntry> = Vec::new();
    for v in ErrorCode::iter() {
        let code: &'static str = v.into(); // IntoStaticStr，遵守 serialize 注解
        let stated_exit = error_code_to_exit(code).unwrap_or(-1);
        error_codes.push(ErrorCodeEntry { code, stated_exit });
    }

    EnumSourceMaps { exit_codes, error_codes }
}

/// 错误码字符串 → 退出码数值的声明（aliases，与既有 `ssot.rs::build_error_to_exit` 同形）。
///
/// 错误码字符串 → 退出码数值。
///
/// 05 治理默认化（V2 默认）：退出码由 `ErrorCatalog` 类别派生，不再按实体细分——`ErrorCatalog`
/// 是错误 ID → 类别唯一绑定源，`ErrorCategory::exit_code()` 是退出码唯一派生落点
/// （errors 层唯一权威）。本表因此从"spec-gen 侧 aliases"收敛为**直接读 `ErrorCatalog`**
/// 类别派生，消除按实体独立退码。V1 per-entity 码仍保留在 `ExitCode` enum（弃用兼容路径，
/// 不在默认 `error-codes.md`「对应退出码」列体现）。
fn error_code_to_exit(code: &str) -> Option<i32> {
    ErrorCatalog::exit_code(code)
}

/// `ExitCode` 变体名（PascalCase，仅供 spec-gen 报告用，非契约字符串）。
///
/// `ExitCode` 无 strum serialize（design D1：退出码无字符串契约）。变体名取自
/// `format!("{:?}", v)` 的 Debug 输出（如 `ContentModifiedExternally`），仅供
/// spec-gen 对账报告标注变体，不写入 `exit-codes.md` 契约字符串列。
fn variant_name_exit(v: ExitCode) -> &'static str {
    // ExitCode 是 Copy enum，变体集合编译期已知，用静态匹配返回 &'static str
    // （避免 format! 分配，且变体名仅供报告非契约）。
    match v {
        ExitCode::Success => "Success",
        ExitCode::Usage => "Usage",
        ExitCode::PreconditionBlocked => "PreconditionBlocked",
        ExitCode::ResourceConflict => "ResourceConflict",
        ExitCode::ExternalModification => "ExternalModification",
        ExitCode::NotFound => "NotFound",
        ExitCode::FileNotFound => "FileNotFound",
        ExitCode::ChapterNotFound => "ChapterNotFound",
        ExitCode::ContentModifiedExternally => "ContentModifiedExternally",
        ExitCode::InvalidStateTransition => "InvalidStateTransition",
        ExitCode::ThreadNameConflict => "ThreadNameConflict",
        ExitCode::MainplotNodeNotFound => "MainplotNodeNotFound",
        ExitCode::ThreadNotFound => "ThreadNotFound",
        ExitCode::EmergenceNotFound => "EmergenceNotFound",
        ExitCode::BindingAlreadyExists => "BindingAlreadyExists",
        ExitCode::EmergenceArchived => "EmergenceArchived",
        ExitCode::Storage => "Storage",
    }
}

impl EnumSourceMaps {
    /// 渲染 `exit-codes.md` §A「退出码」列 + 「变体名（debug）」对账片段。
    ///
    /// 只含机器可导出列（退出码数值 + 变体名），不含中文「类别/含义/固化切片」叙述列
    /// （后者仍手写，见 design Q1）。生成物用于与手写 md 对账，非整表覆盖。
    pub fn render_exit_codes_fragment(&self) -> String {
        let mut s = String::new();
        s.push_str("<!-- @generated by spec-gen enum_source. 对账片段，非手写 md 全表。 -->\n");
        s.push_str("<!-- 退出码数值唯一源：novel_cli::errors::ExitCode 判别式。 -->\n");
        s.push_str("| 退出码 | 变体名(debug) |\n");
        s.push_str("|---|---|\n");
        for e in &self.exit_codes {
            s.push_str(&format!("| `{}` | {} |\n", e.code, e.variant));
        }
        s
    }

    /// 渲染 `error-codes.md` §A「错误码」+「对应退出码」列对账片段。
    ///
    /// 只含机器可导出列（错误码字符串 + 对应退出码数值），不含中文「含义/固化切片」
    /// 叙述列。错误码字符串源 `ErrorCode` strum serialize（逐字等于原 `as_str()`），
    /// 对应退出码源 spec-gen 侧 aliases（errors 层 `exit_code()` 仍唯一权威）。
    pub fn render_error_codes_fragment(&self) -> String {
        let mut s = String::new();
        s.push_str("<!-- @generated by spec-gen enum_source. 对账片段，非手写 md 全表。 -->\n");
        s.push_str("<!-- 错误码字符串唯一源：novel_cli::errors::ErrorCode strum serialize。 -->\n");
        s.push_str("<!-- 对应退出码源：spec-gen aliases（errors::exit_code() 仍唯一权威）。 -->\n");
        s.push_str("| 错误码 | 对应退出码 |\n");
        s.push_str("|---|---|\n");
        for e in &self.error_codes {
            let exit = if e.stated_exit >= 0 {
                format!("`{}`", e.stated_exit)
            } else {
                "（未声明）".to_string()
            };
            s.push_str(&format!("| `{}` | {} |\n", e.code, exit));
        }
        s
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exit_codes_fragment_contains_all_17_discriminants() {
        let maps = load_enum_source();
        assert_eq!(maps.exit_codes.len(), 17, "ExitCode 应有 17 个变体");
        let codes: Vec<i32> = maps.exit_codes.iter().map(|e| e.code).collect();
        // 判别式数值集合逐字不变（契约语义零变更）
        assert!(codes.contains(&0));
        assert!(codes.contains(&5));
        assert!(codes.contains(&21));
        assert!(codes.contains(&70));
    }

    #[test]
    fn error_codes_fragment_strings_match_original_as_str() {
        let maps = load_enum_source();
        // 33 个错误码字符串（strum serialize 逐字等于原手写 as_str）
        assert_eq!(maps.error_codes.len(), 33, "ErrorCode 应有 33 个变体");
        let codes: Vec<&str> = maps.error_codes.iter().map(|e| e.code).collect();
        assert!(codes.contains(&"external_modification"));
        assert!(codes.contains(&"content_modified_externally"));
        assert!(codes.contains(&"state_conflict"));
        assert!(codes.contains(&"context_budget_exceeded"));
        // 通用码 external_modification→5，细分码 content_modified_externally→21（slice-01 对齐基线）
        let ext = maps.error_codes.iter().find(|e| e.code == "external_modification").unwrap();
        assert_eq!(ext.stated_exit, 5);
        let cme = maps.error_codes.iter().find(|e| e.code == "content_modified_externally").unwrap();
        assert_eq!(cme.stated_exit, 21);
    }
}
